"""Corpus-wide evaluation — run the distiller over all 18 Andersen volumes and
aggregate metrics into a Markdown report (plan-v3 §12).

Reuses the library functions (no orchestration duplication). Network-free: the
external connector is not invoked here. Run:

    python3 corpus_eval.py --data /path/to/svNames/data --out eval/corpus_report.md
"""

from __future__ import annotations

import argparse
import glob
import os
import re

from tei_comments import (
    load_volume, load_place_register, load_person_register, normalize,
    strip_markup, _PLACE,
)
from classify import classify
from reconcile import reconcile_place, reconcile_person
import register_index as rix

DEFAULT_DATA = "/home/user/svNames/data"


def _vol_no(path: str) -> int:
    m = re.search(r"Andersen (\d+)", os.path.basename(path))
    return int(m.group(1)) if m else 999


def gold_surfaces_by_vol(data_dir: str) -> dict[int, set[str]]:
    """Map volume number -> set of normalized body placeName surfaces.

    The canonical `Andersen N` files carry no `ref="geo-*"` tags; the linked
    placeNames live only in the travelogue working files (`noHiSeg_*` vol 14,
    `commentHiSeg*` vol 15). Pull the gold set from whichever sibling has them.
    """
    out: dict[int, set[str]] = {}
    for p in glob.glob(os.path.join(data_dir, "*.xml")):
        base = os.path.basename(p)
        if base.startswith("Andersen "):
            continue  # canonical reading text — no geo refs
        with open(p, encoding="utf-8", errors="replace") as fh:
            txt = fh.read()
        if '<placeName ref="geo-' not in txt:
            continue
        m = re.search(r"Andersen[_ ](\d+)", base)
        if not m:
            continue
        surfaces = {normalize(strip_markup(s)) for _, s in _PLACE.findall(txt)}
        out[int(m.group(1))] = surfaces
    return out


def process_volume(path: str, register, persons, gold: set[str]) -> dict:
    vol = load_volume(path)
    # Anchor classification on body placeName surfaces + the register + the gold
    # set (canonical reading texts carry no geo refs, so gold comes from a
    # travelogue sibling — see gold_surfaces_by_vol).
    place_keys = set(vol.place_surface_norm) | gold
    if register:
        place_keys |= set(register)
    distilled = [classify(r, place_keys) for r in vol.rows]

    ne = sum(1 for d in distilled if d.is_named_entity)
    place_rows = [d for d in distilled if any(e.etype == "place" for e in d.entities)]
    person_rows = [d for d in distilled if any(e.etype == "person" for e in d.entities)]

    place_linked = sum(1 for d in place_rows if register and reconcile_place(d, register))
    person_linked = sum(1 for d in person_rows if persons and reconcile_person(d, persons))

    # place P/R against tagged-place lemmas (gold from the travelogue siblings)
    gold_rids = {d.row.rid for d in distilled if normalize(d.row.lemma) in gold}
    pred = {d.row.rid for d in place_rows}
    tp = len(gold_rids & pred)
    rec = tp / len(gold_rids) if gold_rids else None

    return {
        "vol": _vol_no(path),
        "name": os.path.basename(path),
        "rows": len(distilled),
        "ne": ne,
        "place_rows": len(place_rows),
        "place_linked": place_linked,
        "person_rows": len(person_rows),
        "person_linked": person_linked,
        "gold_places": len(gold_rids),
        "place_recall": rec,
    }


def build_report(data_dir: str) -> tuple[str, list[dict]]:
    register = load_place_register(os.path.join(data_dir, "registers", "places.xml"))
    persons = load_person_register(os.path.join(data_dir, "registers", "persons.xml"))
    gold_by_vol = gold_surfaces_by_vol(data_dir)

    vols = sorted(glob.glob(os.path.join(data_dir, "Andersen [0-9]* - *_w_notes*.xml")),
                  key=_vol_no)
    stats = [process_volume(p, register, persons, gold_by_vol.get(_vol_no(p), set()))
             for p in vols]
    stats = [s for s in stats if s["rows"] > 0]

    def pct(a, b):
        return f"{100*a/b:.0f}%" if b else "—"

    lines = [
        "# Corpus evaluation — all 18 Andersen volumes",
        "",
        "Generated by `corpus_eval.py` over the svNames editorial comments "
        "(`<table rend=\"textcomments\">`). Internal reconciliation only "
        "(no network / external authorities).",
        "",
        f"- place register keys: **{len(register)}**  ·  "
        f"person register keys: **{len(persons)}**",
        "",
        "| Vol | Title | Rows | NE | Place | linked | Person | linked | P-recall* |",
        "| ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    tot = {k: 0 for k in ("rows", "ne", "place_rows", "place_linked",
                          "person_rows", "person_linked", "gold_places")}
    for s in stats:
        title = re.sub(r"_w_notes.*", "", s["name"]).replace(f"Andersen {s['vol']} - ", "")
        rec = f"{s['place_recall']:.2f}" if s["place_recall"] is not None else "—"
        lines.append(
            f"| {s['vol']} | {title} | {s['rows']} | {pct(s['ne'], s['rows'])} | "
            f"{s['place_rows']} | {pct(s['place_linked'], s['place_rows'])} | "
            f"{s['person_rows']} | {pct(s['person_linked'], s['person_rows'])} | {rec} |"
        )
        for k in tot:
            tot[k] += s[k]

    lines += [
        f"| **all** | **18 volumes** | **{tot['rows']}** | "
        f"**{pct(tot['ne'], tot['rows'])}** | **{tot['place_rows']}** | "
        f"**{pct(tot['place_linked'], tot['place_rows'])}** | **{tot['person_rows']}** | "
        f"**{pct(tot['person_linked'], tot['person_rows'])}** | |",
        "",
        "\\* Place recall = share of exactly-tagged-place lemmas the distiller "
        "marks as a place. A gold set exists only where the source has injected "
        "`placeName ref=\"geo-*\"` tags — in practice just volume 14 "
        "(`noHiSeg_*`); no other volume, vol 15 included, carries them.",
        "",
        f"Totals: **{tot['rows']:,}** comment rows · "
        f"**{tot['ne']:,}** named-entity rows · "
        f"**{tot['person_linked']:,}** person mentions linked to the register · "
        f"**{tot['place_linked']:,}** place mentions linked.",
    ]
    return "\n".join(lines) + "\n", stats


def index_authority_lift(data_dir: str) -> str:
    """Measure the person-linkage lift from adding the sub-series Navneregister
    entries as an extra authority (alongside persons.xml)."""
    base = load_person_register(os.path.join(data_dir, "registers", "persons.xml"))
    by_series = rix.parse_corpus(data_dir)
    all_entries = [e for es in by_series.values() for e in es]
    idx_auth = rix.to_authority_index(all_entries)

    augmented = {k: set(v) for k, v in base.items()}
    for k, ids in idx_auth.items():
        augmented.setdefault(k, set()).update(ids)

    smap, vser = rix.build_series_map(data_dir)
    vols = sorted(glob.glob(os.path.join(data_dir, "Andersen [0-9]* - *_w_notes*.xml")),
                  key=_vol_no)
    lines = [
        "# Person-linkage lift from sub-series Navneregister authority",
        "",
        f"persons.xml keys: **{len(base)}**  →  + Navneregister "
        f"({len(all_entries)} entries): **{len(augmented)}** keys",
        "",
        "| Vol | Series | Person rows | linked (persons.xml) | linked (+ index) |",
        "| ---: | --- | ---: | ---: | ---: |",
    ]
    tb = ta = tr = 0
    for p in vols:
        vol = load_volume(p)
        keys = set(vol.place_surface_norm)
        dist = [classify(r, keys) for r in vol.rows]
        prows = [d for d in dist if any(e.etype == "person" for e in d.entities)]
        lb = sum(1 for d in prows if reconcile_person(d, base))
        la = sum(1 for d in prows if reconcile_person(d, augmented))
        if not prows:
            continue
        n = _vol_no(p)
        lines.append(f"| {n} | {vser.get(n,'')} | {len(prows)} | {lb} | {la} |")
        tb += lb
        ta += la
        tr += len(prows)
    lines.append(f"| **all** | | **{tr}** | **{tb}** | **{ta}** |")
    lines.append("")
    lines.append(f"Corpus person linkage: **{tb}/{tr}** ({100*tb/tr:.0f}%) with "
                 f"persons.xml alone → **{ta}/{tr}** ({100*ta/tr:.0f}%) with the "
                 f"sub-series Navneregister folded in (+{ta-tb} mentions).")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default=DEFAULT_DATA, help="svNames data directory")
    ap.add_argument("--out", default="eval/corpus_report.md", help="report path")
    ap.add_argument("--index-lift", default="",
                    help="also write the Navneregister person-linkage lift report")
    args = ap.parse_args(argv)

    report, stats = build_report(args.data)
    if args.out:
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(report)
    print(report)

    if args.index_lift:
        lift = index_authority_lift(args.data)
        with open(args.index_lift, "w", encoding="utf-8") as fh:
            fh.write(lift)
        print(lift)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
